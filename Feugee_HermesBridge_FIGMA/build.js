#!/usr/bin/env node
/* Feugee Hermes Bridge (Figma) - build (no dependencies)
   - dist/code.js : src/main.js
   - dist/ui.html : canonical panel.css (byte-identical, inlined) + bridge.css + ui.js
   Figma accepts ONE html file for the UI, so shared files are inlined here. */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");
const CANON_CSS = path.join(ROOT, "..", "Feugelign_CEP", "css", "panel.css");
const VERSION = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8")).version;
const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8");
fs.mkdirSync(DIST, { recursive: true });

const panelCss = fs.readFileSync(CANON_CSS, "utf8");
const html = read("ui.html")
  .replace("/*@PANEL_CSS*/", () => panelCss)
  .replace("/*@PLUGIN_CSS*/", () => read("bridge.css"))
  .replace("<!--@LOGO-->", () => read("logo.svg.html"))
  .split("/*@VERSION*/").join(VERSION)
  .replace("/*@SCRIPTS*/", () => read("ui.js").replace(/<\/script/gi, "<\\/script"));
fs.writeFileSync(path.join(DIST, "ui.html"), html);

const code = "/* Feugee Hermes Bridge v" + VERSION + " - generated by build.js, edit src/ */\n" +
  read("main.js").split("/*@VERSION*/").join(VERSION);
fs.writeFileSync(path.join(DIST, "code.js"), code);

if (!html.includes(panelCss)) throw new Error("panel.css was altered while inlining");
console.log("built v" + VERSION + "  code.js " + (code.length / 1024).toFixed(1) + " KB  ui.html " + (html.length / 1024).toFixed(1) + " KB");
