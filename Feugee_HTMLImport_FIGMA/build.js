#!/usr/bin/env node
/* Feugee HTML Import - build (no dependencies)
   - dist/code.js   : builder.js + main.js
   - dist/ui.html   : canonical panel.css (byte-identical, inlined) + plugin css + loader/capture/ui js
   - dist/feugee-capture.js : console snippet (capture.js + snippet.js)
   Figma only accepts ONE html file for the UI, so shared files are inlined
   at build time instead of linked. */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");
const CANON_CSS = path.join(ROOT, "..", "Feugelign_CEP", "css", "panel.css");
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const VERSION = pkg.version;

const read = (f) => fs.readFileSync(path.join(SRC, f), "utf8");
fs.mkdirSync(DIST, { recursive: true });

// keep panel.css byte-identical with the CEP suite: inline as-is, never edited
const panelCss = fs.readFileSync(CANON_CSS, "utf8");

const capture = read("capture.js");
const snippet = "/* Feugee HTML Import capture v" + VERSION + " */\n" + capture + "\n" + read("snippet.js");
fs.writeFileSync(path.join(DIST, "feugee-capture.js"), snippet);

const ui = read("ui.js").split("/*@VERSION*/").join(VERSION);
const scripts = [
  "var FEUGEE_SNIPPET = " + JSON.stringify(snippet).replace(/<\/script/gi, "<\\/script") + ";",
  capture,
  read("loader.js"),
  ui
].join("\n;\n").replace(/<\/script/gi, "<\\/script");

let html = read("ui.html")
  .replace("/*@PANEL_CSS*/", () => panelCss)
  .replace("/*@PLUGIN_CSS*/", () => read("htmlimport.css"))
  .replace("<!--@LOGO-->", () => read("logo.svg.html"))
  .replace("/*@VERSION*/", () => VERSION)
  .replace("/*@SCRIPTS*/", () => scripts);
fs.writeFileSync(path.join(DIST, "ui.html"), html);

const code = "/* Feugee HTML Import v" + VERSION + " - generated by build.js, edit src/ */\n" +
  read("builder.js") + "\n;\n" + read("main.js");
fs.writeFileSync(path.join(DIST, "code.js"), code);

// sanity: canonical css really is in there untouched
if (!html.includes(panelCss)) throw new Error("panel.css was altered while inlining");
console.log("built v" + VERSION + "  code.js " + (code.length / 1024).toFixed(1) + " KB  ui.html " +
  (html.length / 1024).toFixed(1) + " KB  snippet " + (snippet.length / 1024).toFixed(1) + " KB");
